"""ctrr: build the cases the web app reads.

    ctrr phantom                 # the synthetic tutorial case, no download
    ctrr fetch-kits --count 5    # download 5 kidney-tumour studies from IDC
    ctrr build-kits              # turn everything fetched into cases
    ctrr index                   # rewrite cases/index.json
    ctrr train-data              # nnU-Net training set from fetched studies (docs/training.md)

Cases are written to ../web/public/cases unless --cases says otherwise.
"""

from __future__ import annotations

import argparse
import logging
import tempfile
from pathlib import Path

from . import idc
from .build import build_case
from .bundle import write_index
from .phantom import make_phantom

HERE = Path(__file__).resolve().parent.parent
DEFAULT_CASES = HERE.parent / "web" / "public" / "cases"
DEFAULT_RAW = HERE / ".data" / "raw"

PHANTOM_SOURCE = {
    "dataset": "Synthetic phantom",
    "collection": None,
    "citation": "Generated by pipeline/ctrr/phantom.py. Not a real patient.",
    "url": None,
    "licence": "MIT",
}


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="ctrr", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cases", type=Path, default=DEFAULT_CASES, help="where cases are written")
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("phantom", help="build the synthetic tutorial case")

    fetch = sub.add_parser("fetch-kits", help="download C4KC-KiTS studies from Imaging Data Commons")
    fetch.add_argument("--raw", type=Path, default=DEFAULT_RAW)
    fetch.add_argument("--count", type=int, default=5)
    fetch.add_argument("--max-slices", type=int, default=300, help="skip studies with more slices than this")
    fetch.add_argument("--patients", nargs="*", help="particular PatientIDs, e.g. KiTS-00002")

    build = sub.add_parser("build-kits", help="build a case from every fetched study")
    build.add_argument("--raw", type=Path, default=DEFAULT_RAW)

    sub.add_parser("index", help="rewrite cases/index.json")

    train = sub.add_parser("train-data", help="write the nnU-Net v2 training set and its validation report")
    train.add_argument("--raw", type=Path, default=HERE / ".data" / "train-raw", help="where fetch-kits put the studies")
    train.add_argument("--out", type=Path, default=HERE / ".data" / "nnUNet_raw", help="nnU-Net's nnUNet_raw folder")
    train.add_argument("--jobs", type=int, default=4, help="cases converted at once (each can take a few GB)")

    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    if args.command == "train-data":  # writes no website cases
        from .train_data import build_training_set  # needs the `train` extra

        summary = build_training_set(args.raw, args.out, jobs=args.jobs)
        print(f"{summary['passed']} of {summary['fetched']} cases passed; "
              f"{summary['train']} train, {summary['test']} test; report in {summary['folder']}/validation.md")
        return

    args.cases.mkdir(parents=True, exist_ok=True)

    if args.command == "phantom":
        with tempfile.TemporaryDirectory() as tmp:
            make_phantom(Path(tmp))
            folder = build_case(
                Path(tmp),
                args.cases,
                case_id="phantom-01",
                title="Tutorial: synthetic abdomen",
                source=PHANTOM_SOURCE,
                truth_note="The phantom's own geometry: these are exactly the lesions drawn into it.",
                description="CT abdomen, portal venous (synthetic)",
            )
        print(f"wrote {folder}")

    elif args.command == "fetch-kits":
        fetched = idc.fetch_kits(args.raw, args.count, args.max_slices, args.patients)
        print(f"{len(fetched)} studies in {args.raw}")

    elif args.command == "build-kits":
        for item in idc._read(args.raw / "fetched.json"):
            fetched = idc.Fetched(**item)
            number = fetched.patient_id.split("-")[-1]
            folder = build_case(
                Path(fetched.study_dir),
                args.cases,
                case_id=f"kits-{number}",
                title=f"Kidney CT {number}",
                source=idc.kits_source(fetched),
                truth_note=(
                    "Semi-automatic outlines of the kidneys and tumours by the KiTS19 team, "
                    "published in C4KC-KiTS. Cysts were not outlined in this dataset."
                ),
                patient=idc.kits_patient(fetched),
                description=f"CT abdomen, {fetched.ct_description or 'unknown phase'} phase",
            )
            print(f"wrote {folder}")

    path = write_index(args.cases)
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
