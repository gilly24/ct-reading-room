import { describe, expect, it } from "vitest";
import { citationParts, licenceUrl } from "./credit";

const KITS =
  "Heller N, Sathianathen N, Kalapara A, et al. Data from C4KC-KiTS [Data set]. " +
  "The Cancer Imaging Archive, 2019. https://doi.org/10.7937/TCIA.2019.IX49E8NX";

describe("licenceUrl", () => {
  it("links Creative Commons licences to their text", () => {
    expect(licenceUrl("CC BY 3.0")).toBe("https://creativecommons.org/licenses/by/3.0/");
    expect(licenceUrl("CC BY 4.0")).toBe("https://creativecommons.org/licenses/by/4.0/");
    expect(licenceUrl("CC BY-NC-SA 4.0")).toBe("https://creativecommons.org/licenses/by-nc-sa/4.0/");
  });

  it("links the phantom's MIT licence to the repository's", () => {
    expect(licenceUrl("MIT")).toBe("https://github.com/gilly24/ct-reading-room/blob/main/LICENSE");
  });

  it("links nothing it does not know", () => {
    expect(licenceUrl("TCIA Restricted")).toBeNull();
    expect(licenceUrl("")).toBeNull();
  });
});

describe("citationParts", () => {
  it("makes the DOI a link and keeps every character", () => {
    const parts = citationParts(KITS);
    expect(parts.map((p) => p.text).join("")).toBe(KITS);
    expect(parts.filter((p) => p.href)).toEqual([
      { text: "https://doi.org/10.7937/TCIA.2019.IX49E8NX", href: "https://doi.org/10.7937/TCIA.2019.IX49E8NX" },
    ]);
  });

  it("leaves a full stop after an address out of the link", () => {
    const parts = citationParts("See https://example.org/a. Then more.");
    expect(parts).toEqual([
      { text: "See " },
      { text: "https://example.org/a", href: "https://example.org/a" },
      { text: ". Then more." },
    ]);
  });

  it("leaves a citation without an address as text", () => {
    const text = "Generated by pipeline/ctrr/phantom.py. Not a real patient.";
    expect(citationParts(text)).toEqual([{ text }]);
  });
});
